#!/usr/bin/env python3
"""Write GRAMMAR-INDEX.md: for each rule of grammar.tsv, its classes, the packets that served it,
its census check, and its pinned tests (tests-rules.tsv, when it exists).  Refuses (exit 1) when a
class, a dispatched item or a test has no rule: every fix is subordinate to a rule (GRAMMAR.md)."""
import csv, os, re, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))


def rows(name):
    p = os.path.join(HERE, name)
    return list(csv.DictReader(open(p, newline=""), delimiter="\t")) if os.path.exists(p) else []


def main():
    grammar = rows("grammar.tsv")
    cls = {r["id"]: r for r in rows("classes.tsv")}
    rule_of = {r["class"]: r["rule"] for r in rows("class-rules.tsv")}
    override = {r["item"]: r["rule"] for r in rows("packet-rules.tsv")}
    problems = [f"class {c} has no rule" for c in cls if c not in rule_of]
    packets = defaultdict(list)
    for src in ("queue.tsv", "dispatch.tsv"):
        for r in rows(src):
            item = r["item"]
            rules = {override[item]} if item in override else {
                rule_of[c] for c in re.split(r"[ ,;+/]+", r.get("classes") or r.get("class") or "") if c in rule_of}
            if not rules:
                problems.append(f"{src} item {item} ({(r.get('classes') or r.get('class') or '')[:40]}) has no rule")
            for rule in rules:
                packets[rule].append(f"{item} ({r.get('status') or r.get('outcome') or ''})")
    tests = defaultdict(list)
    for r in rows("tests-rules.tsv"):
        tests[r["rule"]].append(r["test"])
    out = ["# Grammar index (generated by grammar_index.py; do not edit)", "",
           "Every class, packet and pinned test, under the rule it serves. GRAMMAR.md says how to read it.", ""]
    for g in grammar + [{"rule": "-", "family": "none", "statement": "not a defect, process, or candidate", "check": ""}]:
        r = g["rule"]
        cs = [c for c, rr in rule_of.items() if rr == r]
        out += [f"## {r} ({g['family']})", "", g["statement"], "", f"- census check: {g['check'] or '-'}",
                f"- classes ({len(cs)}): " + ", ".join(f"{c} [{cls[c]['state']}]" for c in cs if c in cls),
                f"- packets ({len(set(packets[r]))}): " + ", ".join(sorted(set(packets[r]))),
                f"- pinned tests ({len(tests[r])})" + ("" if rows("tests-rules.tsv") else ": not yet mapped (tests-rules.tsv)"), ""]
    if problems:
        out += ["## Unassigned", ""] + [f"- {p}" for p in problems]
    open(os.path.join(HERE, "GRAMMAR-INDEX.md"), "w").write("\n".join(out) + "\n")
    print(f"{len(problems)} unassigned")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
